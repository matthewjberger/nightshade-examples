pub fn measure_text(text: &str) -> f32 {
    let mut width = 0.0_f32;
    let mut first = true;
    for character in text.chars() {
        if character == ' ' {
            width += WORD_SPACING;
            first = false;
            continue;
        }
        if !first {
            width += CHAR_SPACING;
        }
        width += CHAR_WIDTH;
        first = false;
    }
    width
}

fn v(x: f32, y: f32) -> Vec2 {
    Vec2::new(x, y)
}
